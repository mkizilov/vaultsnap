#!/bin/sh
# Writes docs/THIRD_PARTY.md: the third-party crates that are linked into the `vaultsnap` binary,
# with their versions, licenses, and repositories, taken from Cargo.lock through `cargo tree`.
#
#   scripts/third-party-inventory.sh           # rewrite docs/THIRD_PARTY.md
#   scripts/third-party-inventory.sh --check   # fail if the file does not match Cargo.lock
#
# Run it whenever Cargo.lock changes. The list covers every platform (`--target all`), normal
# dependencies of the CLI with its default features, and nothing that is only used to build or
# test. It is an inventory, not a notice file: the license texts of these crates are in their
# packages (docs/THIRD_PARTY.md says what a binary release has to add).
#
# CI compares the result with the committed file on Linux and macOS, so it must not depend on the
# machine. Three things used to: the locale (it decides how `sort` orders names, hence the C locale
# below), CARGO_TERM_COLOR (CI sets it to `always`, which turns cargo's " (*)" marker into escape
# sequences, hence `--color never`), and the awk and sort in use (BSD and GNU differ in how they
# break ties and read escapes, hence a total order and plain awk).
set -eu

LC_ALL=C
export LC_ALL

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
mode=${1:-write}
out=docs/THIRD_PARTY.md
tab=$(printf '\t')

work=$(mktemp -d "${TMPDIR:-/tmp}/third-party.XXXXXX")
trap 'rm -rf "$work"' EXIT

cargo tree --color never -p vaultsnap-cli -e normal --target all --prefix none --locked \
    --format '{p}|{l}|{r}' > "$work/tree" 2> "$work/tree.err" || {
    cat "$work/tree.err" >&2
    echo "third-party-inventory.sh: cargo tree failed" >&2
    exit 1
}
sed -e 's/ (\*)$//' -e 's/ (proc-macro)//' "$work/tree" |
    grep -v '^vaultsnap-' |
    sort -u > "$work/raw"
[ -s "$work/raw" ] || {
    cat "$work/tree.err" >&2
    echo "third-party-inventory.sh: cargo tree produced no packages" >&2
    exit 1
}

awk -F'|' '{
    split($1, id, " ")
    version = id[2]
    sub(/^v/, "", version)
    license = ($2 == "") ? "(none declared)" : $2
    repo = ($3 == "") ? "-" : $3
    printf "| %s | %s | %s | %s |\n", id[1], version, license, repo
}' "$work/raw" > "$work/rows"

crates=$(wc -l < "$work/rows" | tr -d ' ')

# Licenses by number of crates, then by name: a total order, so no sort has to break a tie.
awk -F'|' '{
    expr = $4
    sub(/^ +/, "", expr)
    sub(/ +$/, "", expr)
    count[expr]++
}
END {
    for (expr in count) printf "%d\t%s\n", count[expr], expr
}' "$work/rows" |
    sort -t "$tab" -k1,1nr -k2,2 |
    awk -F "$tab" '{ printf "| %s | %d |\n", $2, $1 }' > "$work/counts"

# A crate needs attention if it declares no license, or if a copyleft license is its only choice
# (no permissive id in the expression, or permissive and copyleft joined by AND). A copyleft id
# offered next to permissive ones with OR is a choice; the permissive one is taken.
awk -F'|' '{
    name = $2; sub(/^ +/, "", name); sub(/ +$/, "", name)
    expr = $4; sub(/^ +/, "", expr); sub(/ +$/, "", expr)
    copyleft = (expr ~ /GPL|MPL|EPL|CDDL|SSPL|BUSL/)
    permissive = (expr ~ /MIT|Apache-2\.0|BSD|ISC|Zlib|Unlicense|CC0-1\.0|0BSD/)
    if (expr == "(none declared)") print "ATTENTION\t" name "\tno license declared"
    else if (copyleft && (!permissive || (expr ~ / AND / && expr !~ / OR /))) print "ATTENTION\t" name "\t" expr
    else if (copyleft) print "CHOICE\t" name "\t" expr
}' "$work/rows" > "$work/flags"

# The flagged crates of one kind, as a markdown list.
list() {
    awk -F "$tab" -v kind="$1" '$1 == kind { printf "- `%s`: %s\n", $2, $3 }' "$work/flags"
}

if grep -q '^ATTENTION' "$work/flags"; then
    verdict="**Attention: read these before distributing; a copyleft license is the only option, or none is declared:**

$(list ATTENTION)"
else
    verdict="None of them requires copyleft terms, and every one declares a license."
fi
if grep -q '^CHOICE' "$work/flags"; then
    verdict="$verdict

A copyleft license is offered only as one alternative next to permissive ones, and the permissive terms (MIT or Apache-2.0) are the ones used, by:

$(list CHOICE)"
fi

{
    cat <<EOF
# Third-party software

VaultSnap's own code is released under the MIT license ([\`LICENSE\`](../LICENSE)). A \`vaultsnap\`
binary also contains code from the $crates crates listed below, each under its own license. This
page is generated by \`scripts/third-party-inventory.sh\` from \`Cargo.lock\`; do not edit it by hand,
and regenerate it when \`Cargo.lock\` changes (\`scripts/third-party-inventory.sh --check\` fails if it
is out of date).

It lists the normal dependencies of the command-line program with its default features, for every
platform. Crates used only to build or to test are not part of the binary and are not listed.

$verdict

## What a binary release owes

The licenses below (MIT, Apache-2.0, BSD-3-Clause, ISC, Zlib, Unicode-3.0, and the others in the
counts) require the copyright and license notices to accompany copies of the software, and
Apache-2.0 also requires a crate's \`NOTICE\` file if it has one. **A source checkout owes nothing
here: no third-party code is vendored in this repository** (cargo downloads the crates). **The
release archives built by \`scripts/package.sh\` currently carry only VaultSnap's own \`LICENSE\`**, so
before binaries are published the full license texts of these crates have to be added to them
(ROADMAP.md, item 2). Native code that is compiled into the binary comes with two crates:
\`zstd-sys\` bundles the zstd library (declared BSD-3-Clause; the library is also offered under
GPL-2.0, and the BSD-3-Clause terms are the ones used), and \`aws-lc-sys\` bundles AWS-LC (its
expression below lists ISC, Apache-2.0, MIT, and BSD-3-Clause). \`ring\` is named in \`Cargo.lock\` but
only for crate features VaultSnap does not enable; it is not part of the binary.

## Licenses, counted

| License expression | Crates |
|--------------------|-------:|
EOF
    cat "$work/counts"
    cat <<'EOF'

## Crates

| Crate | Version | License | Repository |
|-------|---------|---------|------------|
EOF
    cat "$work/rows"
} > "$work/page"

if [ "$mode" = "--check" ]; then
    if cmp -s "$work/page" "$out"; then
        echo "$out is up to date ($crates crates)"
        exit 0
    fi
    echo "$out is out of date: run scripts/third-party-inventory.sh and commit the result" >&2
    echo "first differences (committed file, then regenerated):" >&2
    diff -u "$out" "$work/page" | head -40 >&2
    exit 1
fi
cp "$work/page" "$out"
echo "wrote $out ($crates crates)"
